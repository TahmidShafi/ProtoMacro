/* ============================================================
   ProtoMacro — foods-db.js
   Sourced food catalog generated by pipeline/run.py from:
   - Food Composition Table for Bangladesh (Shaheen et al., 2013)
   - USDA FoodData Central (SR Legacy & Foundation Foods, CC0)
   - Curated estimates for unmatched regional/mixed dishes
   ============================================================ */

import catalog from './data/foods.json';

const SOURCE_LABELS = {
  fctb_2013: 'FCT Bangladesh 2013',
  fdc_foundation: 'USDA FDC',
  fdc_sr_legacy: 'USDA FDC',
  curated: 'Estimate'
};

export const FOODS_META = catalog.metadata;

export const FOODS_DB = catalog.foods.map((f) => ({
  id: f.id,
  name: f.name,
  localName: f.local_name || null,
  state: f.state,
  foodGroup: f.food_group || null,
  calories: Math.round(f.per_100g.kcal),
  protein: f.per_100g.protein,
  carbs: f.per_100g.carbs_total,
  fat: f.per_100g.fat,
  fibre: f.per_100g.fibre,
  basis: f.basis,
  brand: SOURCE_LABELS[f.source.dataset] || 'Estimate',
  sourceInfo: f.source,
  qualityFlags: f.quality_flags || [],
  relatedIds: f.related_ids || [],
  tags: f.tags || []
}));
